"""Dirichlet-coefficient data for the window Weil form of an Epstein zeta Z_Q, for any form (principal or not).
With m = min Q and r(m) its multiplicity, F(s) = Z_Q(s) m^s / r(m) = sum_mu a_mu mu^{-s} over mu = n/m (rational, mu >= 1, a_1 = 1).
-F'/F = sum_lambda c_lambda lambda^{-s} over the multiplicative semigroup generated by the mu > 1. Recursion (as in Queen's dh_sinh.py):
   c_nu = a_nu log nu - sum_{mu*lam = nu, mu > 1, lam > 1} a_mu c_lam.
-Z'/Z = log m + (-F'/F); the constant log m moves into the archimedean term:
   Omega_E(0) = log(|D| / (4 pi^2 m^2)) + 2 psi(1/2),  nu_E(u) = 1/sinh(u/2).  Poles at s = 0, 1, the same as for zeta.
Atoms of the window form: weight w = c_lambda lambda^{-1/2} at u = log lambda (u < 2L).
Daniel Toupin / Golden Physics Project, with AI assistance from Grok."""
import math, numpy as np
from fractions import Fraction
import mpmath as mp

def values(Q, X):
    a,b,c = Q; r = {}; M = int(math.isqrt(int(4*X*max(a,c))))+3
    for x in range(-M, M+1):
        for y in range(-M, M+1):
            v = a*x*x+b*x*y+c*y*y
            if 0 < v <= X: r[v] = r.get(v,0)+1
    return r

def atoms(Q, Lmax):
    a,b,c = Q; D = b*b-4*a*c
    X = math.exp(2*Lmax)
    r = values(Q, int(X*min(a,c))+min(a,c)+1)
    m = min(r); rm = r[m]
    amu = {Fraction(n, m): Fraction(k, rm) for n,k in r.items() if Fraction(n,m) <= X}
    gens = sorted(mu for mu in amu if mu > 1)
    S = set(gens); frontier = list(gens)
    while frontier:   # multiplicative closure inside [1, X]
        new = []
        for x in frontier:
            for g in gens:
                y = x*g
                if y > X: break
                if y not in S: S.add(y); new.append(y)
        frontier = new
    S = sorted(S)
    cl = {}
    for nu in S:
        s = float(amu.get(nu, 0))*math.log(nu)
        for mu in gens:
            if mu*mu > nu*1 and mu >= nu: break
            lam = nu/mu
            if lam in cl and lam > 1: s -= float(amu[mu])*cl[lam]
        cl[nu] = s
    us = np.array([math.log(float(nu)) for nu in S]); ws = np.array([cl[nu]*float(nu)**-0.5 for nu in S])
    Om0 = float(mp.log(abs(D)/(4*mp.pi**2*m*m)) + 2*mp.digamma(0.5))
    return us, ws, Om0, m
